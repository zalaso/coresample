//! Compiles a quantized network (`QNetwork`) into an RV32IM assembly program.
//!
//! The program is a `main` for `sw/runtime/crt0.S`: it runs the network on
//! every input sample, compares the outputs with the expected bytes and
//! returns 0, or 1 + the index of the first mismatch. Each layer is a function
//! (`layer<i>_<kind>`), and every instruction belongs to a region naming its
//! operation (see [`asm`]), recorded in the ELF's `.cs_map` section.
//!
//! The code is deliberately plain: loops with bounds checks, no unrolling. It
//! reproduces the Rust int8 reference bit for bit; speed comes later.
//!
//! Register use in layer functions: a0 = input, a1 = output, s0-s11 saved and
//! used for loop state, t0-t6 as scratch. Requantization reads the int32
//! accumulator from s3 and leaves the clamped byte in t0.

pub mod asm;
pub mod elf;

use asm::Asm;
pub use asm::Region;
use coresample_nn::quant::{QConv2d, QLayer, QLinear, QNetwork, Requant};
use std::fmt::Write;

/// A compiled program: assembly text and the meaning of each region.
pub struct Program {
    pub asm: String,
    pub regions: Vec<Region>,
}

impl Program {
    /// Region table as JSON: id, function, layer, operation.
    pub fn regions_json(&self) -> String {
        let rows: Vec<String> = self
            .regions
            .iter()
            .map(|r| {
                let layer = r.layer.map_or("null".to_string(), |l| l.to_string());
                format!(
                    r#"  {{"id": {}, "function": "{}", "layer": {layer}, "op": "{}"}}"#,
                    r.id, r.function, r.op
                )
            })
            .collect();
        format!("[\n{}\n]\n", rows.join(",\n"))
    }
}

/// Compiles `net` for `samples` inputs (uint8, one sample after another) and
/// the outputs it must produce.
pub fn compile(net: &QNetwork, inputs: &[u8], samples: usize, expected: &[u8]) -> Program {
    let in_size: usize = net.input_shape.iter().product();
    assert_eq!(inputs.len(), samples * in_size, "compile: input length");

    // Shapes after each layer, and which layers produce code.
    let mut shapes = vec![net.input_shape.clone()];
    for layer in &net.layers {
        let s = shapes.last().unwrap();
        shapes.push(match layer {
            QLayer::Conv2d(c) => {
                let [_, co, oh, ow] = c.output_shape([1, s[0], s[1], s[2]]);
                vec![co, oh, ow]
            }
            QLayer::MaxPool2d { kernel, stride } => {
                vec![
                    s[0],
                    (s[1] - kernel) / stride + 1,
                    (s[2] - kernel) / stride + 1,
                ]
            }
            QLayer::Flatten => vec![s.iter().product()],
            QLayer::Linear(l) => {
                assert_eq!(
                    s.iter().product::<usize>(),
                    l.inputs,
                    "compile: linear layer input size"
                );
                vec![l.outputs]
            }
        });
    }
    let out_size: usize = shapes.last().unwrap().iter().product();
    assert_eq!(
        expected.len(),
        samples * out_size,
        "compile: expected output length"
    );
    let computing: Vec<usize> = (0..net.layers.len())
        .filter(|&i| !matches!(net.layers[i], QLayer::Flatten))
        .collect();
    assert!(
        !computing.is_empty(),
        "compile: the network has no layer that computes"
    );
    let buf_size = shapes[1..]
        .iter()
        .map(|s| s.iter().product::<usize>())
        .max()
        .unwrap();

    let mut a = Asm::default();
    a.raw("# Generated by coresample-compiler. Do not edit.");
    a.raw("  .option norelax  # keep code sizes fixed, so .cs_map addresses stay exact");
    a.raw("  .text");

    emit_main(&mut a, net, &computing, samples, in_size, out_size);
    let mut data = String::new();
    for &i in &computing {
        let s = &shapes[i];
        match &net.layers[i] {
            QLayer::Conv2d(c) => emit_conv2d(&mut a, &mut data, i, c, [s[0], s[1], s[2]]),
            QLayer::MaxPool2d { kernel, stride } => {
                emit_max_pool(&mut a, i, [s[0], s[1], s[2]], *kernel, *stride)
            }
            QLayer::Linear(l) => emit_linear(&mut a, &mut data, i, l),
            QLayer::Flatten => unreachable!(),
        }
    }

    a.raw("\n  .section .rodata");
    a.raw(&data);
    a.raw(bytes("cs_inputs", inputs.iter().map(|&v| v as i32)));
    a.raw(bytes("cs_expected", expected.iter().map(|&v| v as i32)));
    a.raw("\n  .section .bss");
    for name in ["cs_buf0", "cs_buf1"] {
        a.raw(format!("  .p2align 2\n{name}:\n  .space {buf_size}"));
    }
    a.raw(format!(
        "  .p2align 2\ncs_outputs:\n  .space {}",
        samples * out_size
    ));
    let (asm, regions) = a.finish();
    Program { asm, regions }
}

fn layer_name(i: usize, layer: &QLayer) -> String {
    let kind = match layer {
        QLayer::Conv2d(_) => "conv2d",
        QLayer::MaxPool2d { .. } => "max_pool2d",
        QLayer::Flatten => "flatten",
        QLayer::Linear(_) => "linear",
    };
    format!("layer{i}_{kind}")
}

fn emit_main(
    a: &mut Asm,
    net: &QNetwork,
    computing: &[usize],
    samples: usize,
    in_size: usize,
    out_size: usize,
) {
    a.function("main", None, |a| {
        a.region("prologue");
        for ins in [
            "addi sp, sp, -16",
            "sw ra, 12(sp)",
            "sw s0, 8(sp)",
            "sw s1, 4(sp)",
        ] {
            a.i(ins);
        }
        a.region("loop");
        let sample = a.fresh("sample");
        a.i("li s0, 0");
        a.label(&sample);
        // s1 = this sample's input
        a.i("la s1, cs_inputs");
        a.i(format!("li t0, {in_size}"));
        a.i("mul t0, s0, t0");
        a.i("add s1, s1, t0");
        for (k, &i) in computing.iter().enumerate() {
            a.i("mv a0, s1");
            if k + 1 == computing.len() {
                a.i("la a1, cs_outputs");
                a.i(format!("li t0, {out_size}"));
                a.i("mul t0, s0, t0");
                a.i("add a1, a1, t0");
            } else {
                a.i(format!("la a1, cs_buf{}", k % 2));
                a.i("mv s1, a1");
            }
            a.i(format!("call {}", layer_name(i, &net.layers[i])));
        }
        a.i("addi s0, s0, 1");
        a.i(format!("li t0, {samples}"));
        a.i(format!("blt s0, t0, {sample}"));

        a.region("check");
        let (cmp, bad, done) = (a.fresh("cmp"), a.fresh("bad"), a.fresh("done"));
        a.i("la t0, cs_outputs");
        a.i("la t1, cs_expected");
        a.i("li t2, 0");
        a.i(format!("li t3, {}", samples * out_size));
        a.label(&cmp);
        a.i(format!("bge t2, t3, {done}"));
        a.i("add t4, t0, t2");
        a.i("lbu t4, 0(t4)");
        a.i("add t5, t1, t2");
        a.i("lbu t5, 0(t5)");
        a.i(format!("bne t4, t5, {bad}"));
        a.i("addi t2, t2, 1");
        a.i(format!("j {cmp}"));
        a.label(&bad);
        a.i("addi a0, t2, 1");
        let ret = a.fresh("ret");
        a.i(format!("j {ret}"));
        a.label(&done);
        a.i("li a0, 0");

        a.region("epilogue");
        a.label(&ret);
        for ins in [
            "lw ra, 12(sp)",
            "lw s0, 8(sp)",
            "lw s1, 4(sp)",
            "addi sp, sp, 16",
            "ret",
        ] {
            a.i(ins);
        }
    });
}

const SAVED: [&str; 12] = [
    "s0", "s1", "s2", "s3", "s4", "s5", "s6", "s7", "s8", "s9", "s10", "s11",
];

/// Saves s0-s11 and copies the input and output pointers to s10 and s9.
fn prologue(a: &mut Asm) {
    a.region("prologue");
    a.i("addi sp, sp, -48");
    for (k, r) in SAVED.iter().enumerate() {
        a.i(format!("sw {r}, {}(sp)", 4 * k));
    }
    a.i("mv s10, a0");
    a.i("mv s9, a1");
}

fn epilogue(a: &mut Asm) {
    a.region("epilogue");
    for (k, r) in SAVED.iter().enumerate() {
        a.i(format!("lw {r}, {}(sp)", 4 * k));
    }
    a.i("addi sp, sp, 48");
    a.i("ret");
}

/// `reg += 1; if reg < limit goto target`.
fn loop_back(a: &mut Asm, reg: &str, limit: usize, target: &str) {
    a.i(format!("addi {reg}, {reg}, 1"));
    a.i(format!("li t0, {limit}"));
    a.i(format!("blt {reg}, t0, {target}"));
}

/// t0 = clamp(round_half_up(s3 * m0 / 2^shift) + y_zp, lo, 255), exactly as
/// `Requant::apply` in the Rust reference. The 64-bit product is mulh:mul.
fn emit_requant(a: &mut Asm, rq: Requant, y_zero_point: i32, lo: i32) {
    a.region("requant");
    a.i(format!("li t1, {}", rq.m0));
    a.i("mul t2, s3, t1"); // low word
    a.i("mulh t3, s3, t1"); // high word (signed x signed)
                            // + 2^(shift - 1), carried into the high word
    let bit = rq.shift - 1;
    if bit < 32 {
        a.i(format!("li t4, {}", (1u32 << bit) as i32));
        a.i("add t5, t2, t4");
        a.i("sltu t6, t5, t2");
        a.i("add t3, t3, t6");
        a.i("mv t2, t5");
    } else {
        a.i(format!("li t4, {}", 1u32 << (bit - 32)));
        a.i("add t3, t3, t4");
    }
    // >> shift (arithmetic), keeping the low 32 bits
    if rq.shift >= 32 {
        a.i(format!("srai t0, t3, {}", rq.shift - 32));
    } else {
        a.i(format!("srli t0, t2, {}", rq.shift));
        a.i(format!("slli t4, t3, {}", 32 - rq.shift));
        a.i("or t0, t0, t4");
    }
    a.i(format!("addi t0, t0, {y_zero_point}"));
    let (ok_lo, ok_hi) = (a.fresh("clamp_lo"), a.fresh("clamp_hi"));
    a.i(format!("li t1, {lo}"));
    a.i(format!("bge t0, t1, {ok_lo}"));
    a.i("mv t0, t1");
    a.label(&ok_lo);
    a.i("li t1, 255");
    a.i(format!("ble t0, t1, {ok_hi}"));
    a.i("mv t0, t1");
    a.label(&ok_hi);
}

fn store_byte(a: &mut Asm, reg: &str) {
    a.region("store");
    a.i(format!("sb {reg}, 0(s9)"));
    a.i("addi s9, s9, 1");
}

fn emit_conv2d(a: &mut Asm, data: &mut String, li: usize, c: &QConv2d, [cin, h, w]: [usize; 3]) {
    let [_, cout, oh, ow] = c.output_shape([1, cin, h, w]);
    let (kh, kw) = c.kernel;
    let (s, p) = (c.stride, c.padding);
    let (wsym, bsym) = (format!("cs_l{li}_w"), format!("cs_l{li}_b"));
    data.push_str(&bytes(&wsym, c.weight.iter().map(|&v| v as i32)));
    data.push_str(&words(&bsym, &c.bias));
    let lo = if c.relu { c.y_zero_point.max(0) } else { 0 };

    a.function(&format!("layer{li}_conv2d"), Some(li), |a| {
        prologue(a);
        let [l_co, l_oy, l_ox, l_ci, l_ky, l_kx, l_skip] =
            ["co", "oy", "ox", "ci", "ky", "kx", "skip"].map(|n| a.fresh(n));
        a.region("loop");
        a.i("li s0, 0"); // s0 = output channel
        a.label(&l_co);
        a.i(format!("la t0, {wsym}"));
        a.i(format!("li t1, {}", cin * kh * kw));
        a.i("mul t1, s0, t1");
        a.i("add s8, t0, t1"); // s8 = weights of this output channel
        a.i("li s1, 0"); // s1 = output row
        a.label(&l_oy);
        a.i("li s2, 0"); // s2 = output column
        a.label(&l_ox);

        a.region("bias");
        a.i(format!("la t0, {bsym}"));
        a.i("slli t1, s0, 2");
        a.i("add t0, t0, t1");
        a.i("lw s3, 0(t0)"); // s3 = accumulator

        a.region("mac");
        a.i("mv s7, s8"); // s7 walks the weights in (ci, ky, kx) order
        a.i("li s4, 0"); // s4 = input channel
        a.label(&l_ci);
        a.i("li s5, 0"); // s5 = ky
        a.label(&l_ky);
        a.i(format!("li t0, {s}"));
        a.i("mul t0, s1, t0");
        a.i("add t0, t0, s5");
        a.i(format!("addi s11, t0, -{p}")); // s11 = input row
        a.i("li s6, 0"); // s6 = kx
        a.label(&l_kx);
        // Taps in the padding read a real zero: they add nothing, skip them.
        a.i(format!("bltz s11, {l_skip}"));
        a.i(format!("li t0, {h}"));
        a.i(format!("bge s11, t0, {l_skip}"));
        a.i(format!("li t0, {s}"));
        a.i("mul t0, s2, t0");
        a.i("add t0, t0, s6");
        a.i(format!("addi t1, t0, -{p}")); // t1 = input column
        a.i(format!("bltz t1, {l_skip}"));
        a.i(format!("li t0, {w}"));
        a.i(format!("bge t1, t0, {l_skip}"));
        a.i(format!("li t0, {h}"));
        a.i("mul t0, s4, t0");
        a.i("add t0, t0, s11");
        a.i(format!("li t2, {w}"));
        a.i("mul t0, t0, t2");
        a.i("add t0, t0, t1");
        a.i("add t0, t0, s10");
        a.i("lbu t0, 0(t0)");
        a.i(format!("addi t0, t0, -{}", c.x_zero_point));
        a.i("lb t2, 0(s7)");
        a.i("mul t0, t0, t2");
        a.i("add s3, s3, t0");
        a.label(&l_skip);
        a.i("addi s7, s7, 1");
        loop_back(a, "s6", kw, &l_kx);
        loop_back(a, "s5", kh, &l_ky);
        loop_back(a, "s4", cin, &l_ci);

        emit_requant(a, c.requant, c.y_zero_point, lo);
        store_byte(a, "t0");

        a.region("loop");
        loop_back(a, "s2", ow, &l_ox);
        loop_back(a, "s1", oh, &l_oy);
        loop_back(a, "s0", cout, &l_co);
        epilogue(a);
    });
}

fn emit_linear(a: &mut Asm, data: &mut String, li: usize, l: &QLinear) {
    let (wsym, bsym) = (format!("cs_l{li}_w"), format!("cs_l{li}_b"));
    // Stored transposed, (outputs, inputs), so each output reads its weights in order.
    let transposed =
        (0..l.outputs).flat_map(|o| (0..l.inputs).map(move |i| l.weight[i * l.outputs + o] as i32));
    data.push_str(&bytes(&wsym, transposed));
    data.push_str(&words(&bsym, &l.bias));
    let lo = if l.relu { l.y_zero_point.max(0) } else { 0 };

    a.function(&format!("layer{li}_linear"), Some(li), |a| {
        prologue(a);
        let [l_o, l_i] = ["o", "i"].map(|n| a.fresh(n));
        a.region("loop");
        a.i("li s0, 0"); // s0 = output
        a.label(&l_o);

        a.region("bias");
        a.i(format!("la t0, {bsym}"));
        a.i("slli t1, s0, 2");
        a.i("add t0, t0, t1");
        a.i("lw s3, 0(t0)");

        a.region("mac");
        a.i(format!("la t0, {wsym}"));
        a.i(format!("li t1, {}", l.inputs));
        a.i("mul t1, s0, t1");
        a.i("add s7, t0, t1"); // s7 = weights of this output
        a.i("li s4, 0"); // s4 = input
        a.label(&l_i);
        a.i("add t0, s10, s4");
        a.i("lbu t0, 0(t0)");
        a.i(format!("addi t0, t0, -{}", l.x_zero_point));
        a.i("lb t1, 0(s7)");
        a.i("mul t0, t0, t1");
        a.i("add s3, s3, t0");
        a.i("addi s7, s7, 1");
        loop_back(a, "s4", l.inputs, &l_i);

        emit_requant(a, l.requant, l.y_zero_point, lo);
        store_byte(a, "t0");

        a.region("loop");
        loop_back(a, "s0", l.outputs, &l_o);
        epilogue(a);
    });
}

fn emit_max_pool(a: &mut Asm, li: usize, [c, h, w]: [usize; 3], k: usize, s: usize) {
    let (oh, ow) = ((h - k) / s + 1, (w - k) / s + 1);
    a.function(&format!("layer{li}_max_pool2d"), Some(li), |a| {
        prologue(a);
        let [l_c, l_oy, l_ox, l_ky, l_kx, l_keep] =
            ["c", "oy", "ox", "ky", "kx", "keep"].map(|n| a.fresh(n));
        a.region("loop");
        a.i("li s0, 0"); // s0 = channel
        a.label(&l_c);
        a.i("li s1, 0"); // s1 = output row
        a.label(&l_oy);
        a.i("li s2, 0"); // s2 = output column
        a.label(&l_ox);

        a.region("max");
        a.i("li s3, 0"); // s3 = running maximum (uint8, so 0 is the floor)
        a.i("li s5, 0"); // s5 = ky
        a.label(&l_ky);
        a.i("li s6, 0"); // s6 = kx
        a.label(&l_kx);
        // index = (c * h + oy * s + ky) * w + ox * s + kx
        a.i(format!("li t0, {h}"));
        a.i("mul t0, s0, t0");
        a.i(format!("li t1, {s}"));
        a.i("mul t1, s1, t1");
        a.i("add t0, t0, t1");
        a.i("add t0, t0, s5");
        a.i(format!("li t1, {w}"));
        a.i("mul t0, t0, t1");
        a.i(format!("li t1, {s}"));
        a.i("mul t1, s2, t1");
        a.i("add t0, t0, t1");
        a.i("add t0, t0, s6");
        a.i("add t0, t0, s10");
        a.i("lbu t0, 0(t0)");
        a.i(format!("bgeu s3, t0, {l_keep}"));
        a.i("mv s3, t0");
        a.label(&l_keep);
        loop_back(a, "s6", k, &l_kx);
        loop_back(a, "s5", k, &l_ky);

        store_byte(a, "s3");

        a.region("loop");
        loop_back(a, "s2", ow, &l_ox);
        loop_back(a, "s1", oh, &l_oy);
        loop_back(a, "s0", c, &l_c);
        epilogue(a);
    });
}

fn bytes(name: &str, values: impl Iterator<Item = i32>) -> String {
    let v: Vec<String> = values.map(|x| x.to_string()).collect();
    let mut s = format!("  .p2align 2\n{name}:\n");
    for chunk in v.chunks(16) {
        let _ = writeln!(s, "  .byte {}", chunk.join(", "));
    }
    s
}

fn words(name: &str, values: &[i32]) -> String {
    let v: Vec<String> = values.iter().map(|x| x.to_string()).collect();
    let mut s = format!("  .p2align 2\n{name}:\n");
    for chunk in v.chunks(8) {
        let _ = writeln!(s, "  .word {}", chunk.join(", "));
    }
    s
}
