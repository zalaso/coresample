#!/usr/bin/env python3
"""Generate inputs and expected outputs for sw/programs/dense_int8.

One int8 dense layer, the way a quantized network runs it:
    acc = W x + b                      (int8 x int8 -> int32)
    y   = relu(clamp((acc * MULT) >> SHIFT, -128, 127))
The expected output is computed here, independently of the C code, so the
program can check itself on the core and on Spike.
"""
import argparse
import random

BATCH, IN, OUT = 4, 16, 8
MULT, SHIFT = 19260, 22  # requantization scale, about 0.0046


def reference(x, w, b):
    y = []
    for row in x:
        out = []
        for o in range(OUT):
            acc = sum(w[o][i] * row[i] for i in range(IN)) + b[o]
            q = (acc * MULT) >> SHIFT  # Python >> on ints is arithmetic, like the C code
            out.append(max(0, min(127, max(-128, q))))
        y.append(out)
    return y


def c_array(name, ctype, rows):
    flat = [v for r in rows for v in (r if isinstance(r, list) else [r])]
    body = ", ".join(str(v) for v in flat)
    return f"static const {ctype} {name}[{len(flat)}] = {{{body}}};\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("out")
    args = ap.parse_args()

    rng = random.Random(args.seed)
    x = [[rng.randint(-128, 127) for _ in range(IN)] for _ in range(BATCH)]
    w = [[rng.randint(-128, 127) for _ in range(IN)] for _ in range(OUT)]
    b = [rng.randint(-20000, 20000) for _ in range(OUT)]
    y = reference(x, w, b)

    with open(args.out, "w") as f:
        f.write("// Generated by scripts/gen_dense_int8.py; do not edit.\n#include <stdint.h>\n")
        f.write(f"#define BATCH {BATCH}\n#define IN {IN}\n#define OUT {OUT}\n")
        f.write(f"#define MULT {MULT}\n#define SHIFT {SHIFT}\n")
        f.write(c_array("X", "int8_t", x))
        f.write(c_array("W", "int8_t", w))
        f.write(c_array("B", "int32_t", b))
        f.write(c_array("Y_EXPECTED", "int8_t", y))


if __name__ == "__main__":
    main()
